# -*- coding: utf-8 -*-
"""
生成纯 ASCII 的 ZScript 宏源码（逐个导出子工具模式）。

输出两个宏文件（每个文件只含一个 [IButton,???,...]，与 ZBrush 自带
Macros/Misc 下全部 21 个官方宏的写法一致，按钮名由文件名决定）：
    zscript/out/Quick Check.TXT   快速检测（每对只记首个相交点）
    zscript/out/Full Check.TXT    完整检测（列出全部相交点）
安装到 ZBrush 的 ZStartup/Macros/Collision Check/ 下。

设计要点（v2，接手后修订）：
1. 文件夹 / 文件名一律 ASCII：ZBrush 用文件名做按钮名，中文文件名在
   非中文区域设置（非 GBK 代码页）的电脑上可能乱码或加载失败。
2. ZScript 编译器会剥离非 ASCII 字面量，中文提示用 StrFromAsc 在运行时
   从 UTF-8 字节构造；每个 StrMerge 最多 10 个参数（#上一段 + 9 字节），
   与已在两版实测可用的第三方 ZScript 插件写法一致。
3. 逐个导出时先 [SubToolSelect,i] 选中该子工具再隐藏其它子工具：
   ZBrush 中“当前选中的子工具”无法被隐藏，若不先选中，每个 sub_i.obj
   都会混入当前选中子工具，导致几乎所有配对都被误报为相交。
   结束后恢复原选中项和原可见性。
4. 优先 ShellExecute 免 Python 的 bin/ZBCollisionEngine.exe（无黑框），
   不存在时回退 run_detect.bat（需要本机装有 Python 3）。
"""

import os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(BASE, "zscript", "out")
MACRO_FOLDER = "Collision Check"      # 安装到 ZStartup/Macros/<此名>/
MACROS = [
    # (文件名, 模式, 中文提示, 英文后备提示)
    ("Quick Check.TXT", "first",
     "快速检测：逐个导出子工具，每对只记录第一处相交点，速度最快。",
     "Quick collision check: first hit per SubTool pair."),
    ("Full Check.TXT", "all",
     "完整检测：逐个导出子工具，列出每对的全部相交点，较慢但信息完整。",
     "Full collision check: all hits per SubTool pair."),
]
CHUNK = 9   # 每个 StrMerge 里的 StrFromAsc 个数上限

S = {
    "note_edit": "请先进入 Edit 编辑模式（按 T 键），再运行碰撞检测。",
    "note_few": "当前工具的子工具数量少于 2 个，无需相交检测。",
    "note_okbtn": "知道了",
    "note_noexe": "未找到检测程序：",
    "note_noexe2": "\n请重新运行安装程序（安装.bat）。工作目录：",
    "note_exportfail": "子工具导出失败。请确认处于 Edit 模式且工具可导出。",
    "progress": "正在导出子工具 ",
    "progress_done": "导出完成，正在检测相交...",
    "note_launched": "检测已启动，中文结果窗口即将弹出，请稍候。",
}

# 英文界面版（python zscript/generate_macro.py --lang en -> zscript/out/en/）
S_EN = {
    "note_edit": "Enter Edit mode first (press T), then run the collision check.",
    "note_few": "This tool has fewer than 2 SubTools, so there is nothing to check.",
    "note_okbtn": "OK",
    "note_noexe": "Check program not found: ",
    "note_noexe2": "\nPlease run the installer again (Install-EN.bat). Working folder: ",
    "note_exportfail": "SubTool export failed. Make sure you are in Edit mode and the tool can be exported.",
    "progress": "Exporting SubTool ",
    "progress_done": "Export finished, checking for intersections...",
    "note_launched": "Check started. The result window will appear shortly.",
}


def cn_lines(var: str, text: str):
    """把中文串拆成多行 VarSet，每个 StrMerge 不超过 10 个参数。"""
    data = list(text.encode("utf-8"))
    out = []
    for i in range(0, len(data), CHUNK):
        parts = ",".join("[StrFromAsc,%d]" % b for b in data[i:i + CHUNK])
        if i == 0:
            out.append("[VarSet,%s,[StrMerge,%s]]" % (var, parts))
        else:
            out.append("[VarSet,%s,[StrMerge,#%s,%s]]" % (var, var, parts))
    return out


def build(mode: str, tip_cn: str, tip_en: str, lang: str = "zh") -> str:
    strings = S_EN if lang == "en" else S
    L = []
    a = L.append
    a("// ZBrush SubTool collision check (%s mode) - PURE ASCII source." % mode)
    a("// Generated by zscript/generate_macro.py - edit the generator, not this file.")
    a("// Chinese strings are built at runtime via StrFromAsc (the ZScript compiler")
    a("// strips non-ASCII literals). Compatible with ZBrush 2022.0.5 / 2025.0.1.")
    a("// Each SubTool is SELECTED, solo-shown and exported to sub_<i>.obj, because")
    a("// OBJ export writes every visible SubTool and the selected one cannot be")
    a("// hidden. Work dir must have NO spaces.")
    a("")
    a('[VarDef,gWorkDir,"C:/ZBCollision/"]')
    a('[VarDef,gMode,"%s"]' % mode)
    a("[VarDef,gStatus(256)]")
    for name in ("vCount", "vi", "vSt", "keep", "ei", "subCount", "dummy",
                 "gOrigSel", "countMem", "countBytes", "modeMem", "modeBytes"):
        a("[VarDef,%s,0]" % name)
    for name in ("subPath", "noteMsg", "batPath", "exePath", "firstSub",
                 "countPath", "modePath"):
        a('[VarDef,%s,""]' % name)
    a("")
    a("// Tooltip: English default, replaced by Chinese at load time.")
    a('[VarDef,s_tip,"%s"]' % tip_en)
    if lang != "en":
        L.extend(cn_lines("s_tip", tip_cn))
    for key in strings:
        a('[VarDef,s_%s,""]' % key)
    a("")
    a("// Chinese runtime strings are (re)built on every press, so they are valid")
    a("// even if top-level statements were skipped at load time.")
    a("[RoutineDef,InitStrings,")
    for key, text in strings.items():
        for line in cn_lines("s_" + key, text):
            a("  " + line)
    a("]")
    a("")
    a("[RoutineDef,SaveVis,")
    a("  [VarSet,vCount,[SubToolGetCount]]")
    a("  [If,(vCount>256),[VarSet,vCount,256]]")
    a("  [VarSet,vi,0]")
    a("  [If,(vCount>0),")
    a("    [Loop,vCount,")
    a("      [VarSet,gStatus(vi),[SubToolGetStatus,vi]]")
    a("      [VarInc,vi]")
    a("    ]")
    a("  ]")
    a("]")
    a("")
    a("// Show ONLY SubTool #keep (keep must already be the selected SubTool).")
    a("// Change only the eye bit 0x01; folder / boolean bits stay intact.")
    a("[RoutineDef,ShowOnly,")
    a("  [VarSet,vi,0]")
    a("  [If,(vCount>0),")
    a("    [Loop,vCount,")
    a("      [VarSet,vSt,[SubToolGetStatus,vi]]")
    a("      [If,(vi=keep),")
    a("        [If,((vSt&1)=0),[SubToolSetStatus,vi,(vSt+1)]]")
    a("      ,")
    a("        [If,((vSt&1)=1),[SubToolSetStatus,vi,(vSt-1)]]")
    a("      ]")
    a("      [VarInc,vi]")
    a("    ]")
    a("  ]")
    a("  [IUpdate,1,1]")
    a("]")
    a("")
    a("[RoutineDef,RestoreVis,")
    a("  [VarSet,vi,0]")
    a("  [If,(vCount>0),")
    a("    [Loop,vCount,")
    a("      [SubToolSetStatus,vi,gStatus(vi)]")
    a("      [VarInc,vi]")
    a("    ]")
    a("  ]")
    a("  [IUpdate,1,1]")
    a("]")
    a("")
    a("[RoutineDef,ShowNote,")
    a("  [NoteIButton,#s_note_okbtn,,,,,,,,,0xffffff,,,]")
    a("  [VarSet,dummy,[Note,noteMsg,,,0x1f1f1f,,,,,,,,]]")
    a("]")
    a("")
    a("[RoutineDef,WriteSmallFile,")
    a("  // writes #noteMsg (ASCII) to #subPath; reuses countMem as buffer")
    a("  [MemDelete,countMem]")
    a("  [MemCreate,countMem,64,0]")
    a("  [VarSet,countBytes,[MemWriteString,countMem,#noteMsg,0]]")
    a("  [MemResize,countMem,(countBytes-1)]")
    a("  [MemSaveToFile,countMem,#subPath,1]")
    a("  [MemDelete,countMem]")
    a("]")
    a("")
    a("[RoutineDef,RunCollisionCheck,")
    a("  [RoutineCall,InitStrings]")
    a('  [If,([IExists,"Transform:Edit"]) && ([IGet,"Transform:Edit"]==0),')
    a("    [VarSet,noteMsg,#s_note_edit]")
    a("    [RoutineCall,ShowNote]")
    a("    [Exit]")
    a("  ]")
    a("  [VarSet,subCount,[SubToolGetCount]]")
    a("  [If,(subCount<2),")
    a("    [VarSet,noteMsg,#s_note_few]")
    a("    [RoutineCall,ShowNote]")
    a("    [Exit]")
    a("  ]")
    a("  [If,(subCount>256),[VarSet,subCount,256]]")
    a("  // Remember selection + visibility, then export each SubTool on its own")
    a("  [VarSet,gOrigSel,[SubToolGetActiveIndex]]")
    a("  [RoutineCall,SaveVis]")
    a("  [VarSet,vCount,subCount]")
    a("  [VarSet,ei,0]")
    a("  [Loop,subCount,")
    a("    [VarSet,vi,(ei+1)]")
    a('    [NoteBar,[StrMerge,#s_progress,vi,"/",subCount],0]')
    a("    [SubToolSelect,ei]")
    a("    [VarSet,keep,ei]")
    a("    [RoutineCall,ShowOnly]")
    a('    [VarSet,subPath,[StrMerge,#gWorkDir,"sub_",ei,".obj"]]')
    a("    [If,[FileExists,#subPath],[FileDelete,#subPath]]")
    a("    [FileNameSetNext,#subPath]")
    a('    [If,[IExists,"Tool:Export"],[IPress,"Tool:Export"]]')
    a("    [VarInc,ei]")
    a("  ]")
    a("  [NoteBar,#s_progress_done,0]")
    a("  [SubToolSelect,gOrigSel]")
    a("  [RoutineCall,RestoreVis]")
    a("  // count.txt: lets the engine ignore stale sub_*.obj from older runs")
    a('  [VarSet,subPath,[StrMerge,#gWorkDir,"count.txt"]]')
    a('  [VarSet,noteMsg,[StrMerge,"",subCount]]')
    a("  [RoutineCall,WriteSmallFile]")
    a("  // mode.txt: first = quick, all = full")
    a('  [VarSet,subPath,[StrMerge,#gWorkDir,"mode.txt"]]')
    a("  [VarSet,noteMsg,#gMode]")
    a("  [RoutineCall,WriteSmallFile]")
    a("  // Launch engine: frozen exe (no Python needed) first, bat as fallback")
    a('  [VarSet,exePath,[StrMerge,#gWorkDir,"bin/ZBCollisionEngine.exe"]]')
    a('  [VarSet,batPath,[StrMerge,#gWorkDir,"run_detect.bat"]]')
    a('  [VarSet,firstSub,[StrMerge,#gWorkDir,"sub_0.obj"]]')
    a("  [If,[FileExists,#firstSub],")
    a("    [If,[FileExists,#exePath],")
    a("      [ShellExecute,#exePath]")
    a("      [NoteBar,#s_note_launched,0]")
    a("    ,")
    a("      [If,[FileExists,#batPath],")
    a("        [ShellExecute,#batPath]")
    a("        [NoteBar,#s_note_launched,0]")
    a("      ,")
    a("        [VarSet,noteMsg,[StrMerge,#s_note_noexe,#exePath,#s_note_noexe2,#gWorkDir]]")
    a("        [RoutineCall,ShowNote]")
    a("      ]")
    a("    ]")
    a("  ,")
    a("    [VarSet,noteMsg,#s_note_exportfail]")
    a("    [RoutineCall,ShowNote]")
    a("  ]")
    a("]")
    a("")
    a("[IButton,???,#s_tip,")
    a("  [IShowActions,0]")
    a("  [IConfig,2022]")
    a("  [RoutineCall,RunCollisionCheck]")
    a(",,1,,,]")
    a("")
    content = "\n".join(L)
    bad = [i + 1 for i, line in enumerate(L) if any(ord(c) > 127 for c in line)]
    if bad:
        raise SystemExit("生成结果含非 ASCII 字符，行：%s" % bad[:5])
    return content


def main(argv=None):
    import sys
    argv = sys.argv[1:] if argv is None else argv
    lang = "en" if "--lang" in argv and argv[argv.index("--lang") + 1:][:1] == ["en"] else "zh"
    out_dir = os.path.join(OUT_DIR, "en") if lang == "en" else OUT_DIR
    os.makedirs(out_dir, exist_ok=True)
    for fname, mode, tip_cn, tip_en in MACROS:
        path = os.path.join(out_dir, fname)
        content = build(mode, tip_cn, tip_en, lang)
        with open(path, "w", encoding="ascii", newline="\n") as fh:
            fh.write(content)
        print("已生成纯 ASCII 宏：%s（%d 字节）" % (path, len(content)))


if __name__ == "__main__":
    main()
